import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { newOutputDirectory } from "./outputDirectory.mjs";
import { bakeOpticalLut, bakeSurfaceEmission, bakeTemporalEmission, encodeRgbaPng, parseObserverCsv } from "./exhaustOptics/bake.mjs";
import { generateEngineSmokeSprite } from "./build-engine-smoke.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
export const generatedOpticalDirectory = path.join(root, "src/flight/aircraft/generated");

export function generateExhaustArtifacts() {
  const profilePath = "scripts/exhaustOptics/f135-visible-approximation.json";
  const observerPath = "scripts/exhaustOptics/data/CIE_xyz_1931_2deg.csv";
  const profileBytes = readFileSync(path.join(root, profilePath));
  const observerBytes = readFileSync(path.join(root, observerPath));
  if (hash(observerBytes) !== "fa663e3535a7e0763a745993a1f0a192eb0275ac46ad2d1befd7626841e713c1") {
    throw new Error("Official CIE observer checksum changed.");
  }
  const profile = JSON.parse(profileBytes.toString());
  const observer = parseObserverCsv(observerBytes);
  const lut = bakeOpticalLut(profile, observer);
  const png = encodeRgbaPng(lut.width, lut.height, lut.rgba);
  const definition = {
    id: profile.id, width: lut.width, height: lut.height, colorSpace: "linear-srgb",
    dry: { firstRow: 0, rowCount: profile.rowsPerMode },
    afterburner: { firstRow: profile.rowsPerMode, rowCount: profile.rowsPerMode },
    hudAccentHex: lut.hudAccentHex,
    ...(profile.surfaceEmission ? { surfaceEmission: bakeSurfaceEmission(profile.surfaceEmission, observer) } : {}),
    ...(profile.temporalEmission ? { temporalEmission: bakeTemporalEmission(profile.temporalEmission) } : {}),
  };
  const metadataTs = Buffer.from("// Generated by scripts/build-exhaust-optics.mjs; do not edit.\n"
    + "// Derived optical data: CC BY-SA 4.0; see f135-exhaust-lut.manifest.json.\n"
    + `export const f135ExhaustOpticalData = ${JSON.stringify(definition, null, 2)} as const;\n`);
  const inputPaths = [profilePath, observerPath, "scripts/exhaustOptics/data/CIE_xyz_1931_2deg.csv_metadata.json",
    "scripts/exhaustOptics/bake.mjs", "scripts/build-exhaust-optics.mjs"];
  const manifest = {
    schemaVersion: 1,
    profile: definition,
    assetLicense: "CC-BY-SA-4.0",
    licenseUrl: "https://creativecommons.org/licenses/by-sa/4.0/",
    attribution: "CIE 2019, Colour-matching functions of CIE 1931 standard colorimetric observer, International Commission on Illumination (CIE), Vienna, AT, DOI:10.25039/CIE.DS.xvudnb9b. Adapted by 0sfs into an assumed emission RGB lookup.",
    rgbMeaning: "Peak-normalized linear-sRGB emission; alpha is separately assumed relative intensity. Not absolute radiance.",
    uvMeaning: "U axial fraction: (0.5+axial*(width-1))/width. V within selected bank: (firstRow+0.5+power*(rowCount-1))/height. Clamp axes; do not filter across banks.",
    orientation: "PNG first/top scanline is dry bank row 0. Use Babylon invertY=false; texture V=0 addresses that first/top row.",
    assumptions: profile.assumptions,
    opticalParameters: { dry: profile.dry, afterburner: profile.afterburner, hudAccentSample: profile.hudAccentSample },
    temporalParameters: profile.temporalEmission,
    surfaceParameters: profile.surfaceEmission,
    sources: profile.sources,
    inputs: inputPaths.map(inputPath => {
      const bytes = readFileSync(path.join(root, inputPath));
      return { path: inputPath, bytes: bytes.length, sha256: hash(bytes) };
    }),
    outputs: [
      { path: "f135-exhaust-lut.png", bytes: png.length, sha256: hash(png) },
      { path: "f135ExhaustOpticalData.ts", bytes: metadataTs.length, sha256: hash(metadataTs) },
    ],
  };
  return {
    "f135-exhaust-lut.png": png,
    "f135ExhaustOpticalData.ts": metadataTs,
    "f135-exhaust-lut.manifest.json": Buffer.from(JSON.stringify(manifest, null, 2) + "\n"),
  };
}

export function checkGeneratedExhaustArtifacts(readInstalled = name => readFileSync(path.join(generatedOpticalDirectory, name))) {
  const files = generateExhaustArtifacts();
  for (const [name, bytes] of Object.entries(files)) {
    const installed = readInstalled(name);
    if (!installed.equals(bytes)) throw new Error(`${name} is stale; run npm run build:exhaust.`);
  }
  return files;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const options = process.argv.slice(2);
  if (options.some(option => !["--install", "--check"].includes(option)) || options.length > 1) {
    throw new Error("Use build-exhaust-optics.mjs [--install | --check].");
  }
  const checking = options[0] === "--check";
  const opticalFiles = checking ? checkGeneratedExhaustArtifacts() : generateExhaustArtifacts();
  const smokeFiles = generateEngineSmokeSprite();
  if (checking) for (const [name, bytes] of Object.entries(smokeFiles)) {
    if (!readFileSync(path.join(generatedOpticalDirectory, name)).equals(bytes)) {
      throw new Error(`${name} is stale; run npm run build:exhaust.`);
    }
  }
  const files = { ...opticalFiles, ...smokeFiles };
  const outputDirectory = newOutputDirectory("exhaust-optics");
  if (!checking) {
    const destination = options[0] === "--install" ? generatedOpticalDirectory : outputDirectory;
    mkdirSync(destination, { recursive: true });
    for (const [name, bytes] of Object.entries(files)) writeFileSync(path.join(destination, name), bytes);
  }
  const report = { mode: options[0] ?? "scratch", success: true,
    artifacts: Object.entries(files).map(([name, bytes]) => ({ name, bytes: bytes.length, sha256: hash(bytes) })) };
  writeFileSync(path.join(outputDirectory, "bake-report.json"), JSON.stringify(report, null, 2) + "\n");
  console.log(JSON.stringify({ ...report, outputDirectory }, null, 2));
}
