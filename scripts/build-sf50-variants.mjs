import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { SF50_VARIANTS } from "../src/flight/aircraft/sf50Variants.ts";

// sf50.xml remains the canonical, editable G1 baseline. The generated packages
// intentionally share its development physics, not a claimed G2/G3 calibration.
const base = readFileSync(new URL("../public/jsbsim-data/aircraft/sf50/sf50.xml", import.meta.url), "utf8");
for (const variant of SF50_VARIANTS.filter(entry => entry.id !== "g1")) {
  const directory = new URL("../public/jsbsim-data/aircraft/" + variant.model + "/", import.meta.url);
  mkdirSync(directory, { recursive: true });
  const model = base
    .replace('<fdm_config name="sf50"', '<fdm_config name="' + variant.model + '"')
    .replace("Cirrus Vision SF50 G1 development JSBSim package.",
      "GENERATED by scripts/build-sf50-variants.mjs. Do not edit this copy.\n  " +
      variant.label + ": shared G1-based development physics, not calibrated for this generation.")
    .replace("Cirrus Vision SF50 G1 FJ33-powered V-tail development model.",
      variant.label + " development package; shared G1 baseline, variant calibration pending.");
  writeFileSync(new URL(variant.model + ".xml", directory), model);
  process.stdout.write("Generated " + variant.model + " from the shared development baseline.\n");
}
